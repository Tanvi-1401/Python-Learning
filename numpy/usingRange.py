#----For 1D Array using arange() function----#
import numpy as np
array = np.arange(1,10)
print(array)

#----For nD Array using arange() function----#
array1 = np.arange(21,27).reshape((2,3))
print(array1)

#----For Zeros and ones----#
zeros = np.zeros((2,3))
ones = np.ones((2,3))
print(zeros)
print(ones)